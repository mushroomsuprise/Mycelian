    /**
     * Build a row of "Emit mock <event>" buttons inside the preview
     * dialog. Each button POSTs to /api/spore-studio/preview/emit and
     * the server pushes one mock socket event into the iframe's sid.
     * Re-rendered whenever the events registry loads (init flow) so
     * the toolbar reflects exactly the events the binding picker can
     * attach actions to.
     */
    function renderPreviewMockToolbar() {
        var host = $("#ss-preview-mocks");
        if (!host) { return; }
        host.innerHTML = "";
        var events = state.registry.events || [];
        if (events.length === 0) {
            var empty = document.createElement("span");
            empty.className = "ss-mocktools-empty";
            empty.textContent = "Loading mock events…";
            host.appendChild(empty);
            return;
        }
        var label = document.createElement("span");
        label.className = "ss-mocktools-empty";
        label.textContent = "Mock:";
        host.appendChild(label);
        events.forEach(function (ev) {
            var btn = document.createElement("button");
            btn.className = "ss-btn ss-btn--ghost";
            btn.textContent = ev.label || ev.event;
            btn.title = "Emit mock '" + ev.event +
                "' over the preview socket";
            btn.addEventListener("click", function () {
                fetch("/api/spore-studio/preview/emit", {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify({
                        token: state.previewToken,
                        event: ev.event,
                    }),
                })
                    .then(function (r) {
                        return r.json().then(function (data) {
                            return { ok: r.ok, data: data };
                        });
                    })
                    .then(function (res) {
                        if (!res.ok) {
                            toast(
                                (res.data && res.data.error) ||
                                    "Mock emit failed",
                                "error"
                            );
                        }
                    })
                    .catch(function () {
                        toast("Mock emit failed", "error");
                    });
            });
            host.appendChild(btn);
        });
    }

    function setupPreviewDialog() {
        var dlg = $("#ss-preview-dialog");
        if (!dlg) { return; }
        var head = dlg.querySelector("[data-drag-handle]");
        var resize = dlg.querySelector("[data-resize-handle]");
        renderPreviewMockToolbar();

        var dragData = null;
        head.addEventListener("mousedown", function (ev) {
            // Header buttons should still be clickable.
            if (ev.target.closest("button")) { return; }
            var rect = dlg.getBoundingClientRect();
            dragData = {
                startX: ev.clientX,
                startY: ev.clientY,
                origLeft: rect.left,
                origTop: rect.top
            };
            ev.preventDefault();
        });
        document.addEventListener("mousemove", function (ev) {
            if (!dragData) { return; }
            var x = dragData.origLeft + (ev.clientX - dragData.startX);
            var y = dragData.origTop + (ev.clientY - dragData.startY);
            x = Math.max(0, Math.min(window.innerWidth - 80, x));
            y = Math.max(0, Math.min(window.innerHeight - 40, y));
            dlg.style.left = x + "px";
            dlg.style.top = y + "px";
        });
        document.addEventListener("mouseup", function () { dragData = null; });

        var resizeData = null;
        resize.addEventListener("mousedown", function (ev) {
            var rect = dlg.getBoundingClientRect();
            resizeData = {
                startX: ev.clientX,
                startY: ev.clientY,
                origW: rect.width,
                origH: rect.height
            };
            ev.preventDefault();
            ev.stopPropagation();
        });
        document.addEventListener("mousemove", function (ev) {
            if (!resizeData) { return; }
            var w = Math.max(280, resizeData.origW + (ev.clientX - resizeData.startX));
            var h = Math.max(200, resizeData.origH + (ev.clientY - resizeData.startY));
            dlg.style.width = w + "px";
            dlg.style.height = h + "px";
        });
        document.addEventListener("mouseup", function () { resizeData = null; });

        var closeBtn = $("#ss-preview-close");
        if (closeBtn) { closeBtn.addEventListener("click", closePreviewDialog); }
        var reloadBtn = $("#ss-preview-reload");
        if (reloadBtn) {
            reloadBtn.addEventListener("click", function () { refreshPreview(true); });
        }
    }

