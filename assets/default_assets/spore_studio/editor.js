    function normalizeModel(model) {
        model = model || {};
        model.template_name = model.template_name || "untitled";
        model.alert_system = model.alert_system === "instant" ? "instant" : "queue";
        model.design = model.design || { width: 800, height: 200 };
        model.design.width = Math.max(
            DESIGN_CANVAS_MIN_PX,
            Number(model.design.width) || 800
        );
        model.design.height = Math.max(
            DESIGN_CANVAS_MIN_PX,
            Number(model.design.height) || 200
        );
        model.elements = Array.isArray(model.elements) ? model.elements : [];
        model.elements.forEach(function (el) {
            el.id = el.id || uuid();
            el.type = el.type || "container";
            el.category = el.category || "Elements";
            // Preserve null position/size — that's how legacy synthetic
            // elements signal "no canvas placement" so the stage skips
            // them and they only appear in the Outline panel.
            if (el.position === undefined) { el.position = { x: 0, y: 0 }; }
            if (el.size === undefined) {
                el.size = DEFAULT_SIZE[el.type] || { w: 100, h: 30 };
            }
            el.props = el.props || {};
            var defsMerge = DEFAULT_PROPS[el.type];
            if (defsMerge) {
                Object.keys(defsMerge).forEach(function (k) {
                    if (el.props[k] === undefined) {
                        el.props[k] = defsMerge[k];
                    }
                });
            }
            el.bindings = el.bindings || [];
            if (!model.legacy) {
                ensureElementExposeDefaults(el);
                ensureElementAnimations(el);
                if (el.type === "text" || el.type === "marquee") {
                    ensureTextModeDefaults(el);
                    normalizeElementFontFamily(el);
                }
                if (el.type === "image") {
                    ensureImageSrcDefaults(el);
                }
                if (el.type === "progress_bar") {
                    ensureProgressBarDefaults(el);
                }
                if (el.type === "shape") { ensureShapeDefaults(el); }
                if (el.type === "divider") { ensureDividerDefaults(el); }
                if (el.type === "gradient") { ensureGradientDefaults(el); }
                if (el.type === "clock") {
                    ensureClockDefaults(el);
                    normalizeElementFontFamily(el);
                }
                if (el.type === "timer") {
                    ensureTimerDefaults(el);
                    normalizeElementFontFamily(el);
                }
                if (pidNorm(el.parent_id)) {
                    ensurePlacementDefaults(el);
                }
            }
            if (model.legacy && el.parent_id) {
                delete el.parent_id;
            }
        });
        normalizeParentLinksAndReorderElements(model);
        model.advanced_js = typeof model.advanced_js === "string" ? model.advanced_js : "";
        if (!model.streamdeck_options || typeof model.streamdeck_options !== "object") {
            model.streamdeck_options = { description: "", actions: {} };
        }
        if (typeof model.streamdeck_options.description !== "string") {
            model.streamdeck_options.description = "";
        }
        var ax = model.streamdeck_options.actions;
        if (typeof ax !== "object" || ax === null || Array.isArray(ax)) {
            model.streamdeck_options.actions = {};
        }
        if (!model.legacy) {
            if (model.duration_seconds === undefined || model.duration_seconds === null) {
                model.duration_seconds = 5;
            } else {
                model.duration_seconds = Number(model.duration_seconds) || 5;
            }
            if (model.queued === undefined) {
                model.queued = false;
            }
            syncDurationWithLayout(model);
        }
        ensureDynamicControls(model);
        return model;
    }

