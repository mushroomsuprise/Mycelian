    function renderStage() {
        var stage = $("#ss-stage");
        stage.innerHTML = "";
        if (!state.model) { return; }
        var design = state.model.design || { width: 800, height: 200 };
        stage.style.width = design.width + "px";
        stage.style.height = design.height + "px";

        (state.model.elements || []).forEach(function (el) {
            if (isLegacyElement(el)) { return; }
            var node = document.createElement("div");
            node.className = "ss-element";
            node.dataset.sporeId = el.id;
            node.dataset.sporeType = el.type;
            var pos = el.position || { x: 0, y: 0 };
            var sz = el.size || { w: 100, h: 30 };
            node.style.left = pos.x + "px";
            node.style.top = pos.y + "px";
            node.style.width = sz.w + "px";
            node.style.height = sz.h + "px";
            applyPropsToNode(node, el);
            if (el.id === state.selectedId) { node.classList.add("selected"); }

            if (el.type === "text") {
                node.textContent = (el.props && el.props.text) || "";
            } else if (el.type === "image") {
                node.textContent = (el.props && el.props.src) ? "img: " + el.props.src : "(image)";
            } else if (el.type === "video") {
                node.textContent = (el.props && el.props.src) ? "video: " + el.props.src : "(video)";
            } else if (el.type === "audio") {
                node.textContent = "&#127925; " + (el.props && el.props.src ? el.props.src : "(audio)");
            } else if (el.type === "container") {
                node.textContent = "";
            }

            var handle = document.createElement("div");
            handle.className = "ss-element__handle ss-element__handle--br";
            node.appendChild(handle);

            attachElementInteractions(node, el, handle);
            stage.appendChild(node);
        });
    }

    function applyPropsToNode(node, el) {
        var props = el.props || {};
        if (props.color) { node.style.color = props.color; }
        if (props.background_color) { node.style.background = props.background_color; }
        if (props.font_size != null) { node.style.fontSize = props.font_size + "px"; }
        if (props.font_family) { node.style.fontFamily = props.font_family; }
        if (props.font_weight) { node.style.fontWeight = props.font_weight; }
        if (props.text_align) { node.style.textAlign = props.text_align; }
        if (props.border_radius != null) { node.style.borderRadius = props.border_radius + "px"; }
        if (props.border_width != null && props.border_color) {
            node.style.border = props.border_width + "px solid " + props.border_color;
        }
        if (props.opacity != null) { node.style.opacity = String(props.opacity); }
    }

    function attachElementInteractions(node, modelEl, handle) {
        var dragData = null;
        node.addEventListener("mousedown", function (ev) {
            if (ev.target === handle) { return; }
            ev.stopPropagation();
            state.selectedId = modelEl.id;
            renderInspector();
            $$(".ss-element", $("#ss-stage")).forEach(function (n) {
                n.classList.toggle("selected", n.dataset.sporeId === modelEl.id);
            });
            dragData = {
                startX: ev.clientX,
                startY: ev.clientY,
                origX: (modelEl.position || {}).x || 0,
                origY: (modelEl.position || {}).y || 0
            };
            ev.preventDefault();
        });
        document.addEventListener("mousemove", function (ev) {
            if (!dragData) { return; }
            var dx = ev.clientX - dragData.startX;
            var dy = ev.clientY - dragData.startY;
            modelEl.position = {
                x: Math.max(0, Math.round(dragData.origX + dx)),
                y: Math.max(0, Math.round(dragData.origY + dy))
            };
            node.style.left = modelEl.position.x + "px";
            node.style.top = modelEl.position.y + "px";
        });
        document.addEventListener("mouseup", function () {
            if (dragData) {
                pushHistoryDebounced();
                modelTouch();
            }
            dragData = null;
        });

        var resizeData = null;
        handle.addEventListener("mousedown", function (ev) {
            ev.stopPropagation();
            resizeData = {
                startX: ev.clientX,
                startY: ev.clientY,
                origW: (modelEl.size || {}).w || 100,
                origH: (modelEl.size || {}).h || 30
            };
            ev.preventDefault();
        });
        document.addEventListener("mousemove", function (ev) {
            if (!resizeData) { return; }
            var dx = ev.clientX - resizeData.startX;
            var dy = ev.clientY - resizeData.startY;
            modelEl.size = {
                w: Math.max(20, Math.round(resizeData.origW + dx)),
                h: Math.max(12, Math.round(resizeData.origH + dy))
            };
            node.style.width = modelEl.size.w + "px";
            node.style.height = modelEl.size.h + "px";
        });
        document.addEventListener("mouseup", function () {
            if (resizeData) {
                pushHistoryDebounced();
                modelTouch();
            }
            resizeData = null;
        });
    }

    var historyTimer = null;
    function pushHistoryDebounced() {
        clearTimeout(historyTimer);
        historyTimer = setTimeout(pushHistory, 250);
    }

