    /*
     * Undo/redo invariant
     * --------------------
     * Every call site in this file follows the pattern:
     *
     *     mutate(state.model);
     *     pushHistory();
     *
     * i.e. ``pushHistory`` snapshots the *post*-mutation model. As a
     * consequence the top of ``state.history`` is always equal to the
     * current ``state.model``. ``undo`` therefore needs to:
     *
     *   1. Pop and discard that "current" snapshot (it's redundant).
     *   2. Save the current model into ``state.future`` for redo.
     *   3. Restore the new top of ``state.history`` as the model.
     *
     * That way the very first Undo click after a change actually moves
     * the model back to the prior version (the prior bug was that it
     * pop'd the current snapshot and restored it as the model, so the
     * UI never visibly changed until the second click).
     *
     * The initial ``loadTemplate`` snapshot guarantees that the very
     * first entry in history is the loaded baseline, so undo bottoms
     * out cleanly when ``history.length <= 1``.
     */
    function pushHistory() {
        if (!state.model) { return; }
        var snapshot = JSON.stringify(state.model);
        var top = state.history.length > 0
            ? state.history[state.history.length - 1]
            : null;
        if (snapshot === top) {
            // Multiple debounced calls landed on the same state — keep
            // the stack lean and don't break the "every entry is a real
            // checkpoint" property used by undo().
            state.future = [];
            return;
        }
        state.history.push(snapshot);
        if (state.history.length > 50) { state.history.shift(); }
        state.future = [];
    }

    function undo() {
        if (!state.model) { return; }
        if (state.history.length <= 1) { return; }
        var current = JSON.stringify(state.model);
        var top = state.history[state.history.length - 1];
        if (current === top) {
            state.history.pop();
        }
        state.future.push(current);
        var prev = state.history[state.history.length - 1];
        state.model = JSON.parse(prev);
        renderAll();
        setDirty(true);
        schedulePreviewDraft();
    }

    function redo() {
        if (!state.model) { return; }
        if (state.future.length === 0) { return; }
        var snapshot = state.future.pop();
        state.history.push(snapshot);
        state.model = JSON.parse(snapshot);
        renderAll();
        setDirty(true);
        schedulePreviewDraft();
    }

    function modelTouch() {
        setDirty(true);
        schedulePreviewDraft();
    }

    var previewDraftTimer = null;
    function postPreviewDraft() {
        if (!state.model || state.model.legacy) {
            return Promise.resolve();
        }
        return fetch("/api/spore-studio/preview/draft", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ token: state.previewToken, model: state.model })
        }).catch(function () { /* best-effort */ });
    }

    function schedulePreviewDraft() {
        if (!previewDialogOpen() || !state.model || state.model.legacy) { return; }
        clearTimeout(previewDraftTimer);
        previewDraftTimer = setTimeout(function () {
            previewDraftTimer = null;
            registerPreviewSession()
                .then(postPreviewDraft)
                .then(function () {
                    var iframe = $("#ss-preview-iframe");
                    if (!iframe || !state.model || !previewDialogOpen()) { return; }
                    var bust = Date.now();
                    iframe.src = "/" + encodeURIComponent(state.model.template_name) +
                        "?__preview_token=" + encodeURIComponent(state.previewToken) +
                        "&_cb=" + bust;
                });
        }, 280);
    }

    function selectedElement() {
        if (!state.model || !state.selectedId) { return null; }
        for (var i = 0; i < state.model.elements.length; i++) {
            if (state.model.elements[i].id === state.selectedId) {
                return state.model.elements[i];
            }
        }
        return null;
    }

    function uniqueElementId(prefix) {
        prefix = prefix || "el";
        state.idCounter += 1;
        var candidate;
        var taken;
        do {
            candidate = prefix + state.idCounter;
            state.idCounter += 1;
            taken = (state.model.elements || []).some(function (e) { return e.id === candidate; });
        } while (taken);
        return candidate;
    }

    function isLegacyElement(el) {
        // JSON-only legacy synthetic elements never get a position when
        // produced by template_parser_back._synthesize_legacy_elements.
        // Those skip canvas rendering and only appear in the Outline.
        return !el || !el.position || el.position.x == null;
    }

    function isLegacyModel() {
        return !!(state.model && state.model.legacy);
    }

    function isReadOnlyLegacyElement(el) {
        // Reverse-parsed legacy elements ARE drawn on the canvas (their
        // position/size live in the model), but every property funnels
        // back into the public JSON config via legacy_bindings. The
        // inspector hides the binding editor and the delete button for
        // these to make the constraint obvious. Any positioned element
        // in a legacy model qualifies — including ones the parser found
        // but couldn't bind to a config field, since deleting them would
        // be a no-op across save+reload anyway.
        return !!(
            isLegacyModel()
            && el
            && el.position
            && el.position.x != null
        );
    }

    function exposeKeysForType(elType) {
        var sch = ELEMENT_PROP_SCHEMA[elType] || [];
        var keys = sch.map(function (e) { return e.key; });
        if (elType === "text") { keys.push("text"); }
        if (["image", "video", "audio"].indexOf(elType) !== -1) {
            keys.push("src");
        }
        return keys;
    }

    function ensureElementExposeDefaults(el) {
        if (!el || el.legacy_bindings || el.legacy_field) { return; }
        if (isLegacyModel()) { return; }
        el.source_settings_expose =
            el.source_settings_expose && typeof el.source_settings_expose === "object"
                ? el.source_settings_expose
                : {};
        exposeKeysForType(el.type || "container").forEach(function (k) {
            if (el.source_settings_expose[k] === undefined) {
                el.source_settings_expose[k] = true;
            }
        });
    }

    function formRowPropWithExpose(el, exportKey, labelText, controlNode) {
        ensureElementExposeDefaults(el);
        if (el.source_settings_expose[exportKey] === undefined) {
            el.source_settings_expose[exportKey] = true;
        }

        var wrap = document.createElement("div");
        wrap.className = "ss-form-prop";
        var head = document.createElement("div");
        head.className = "ss-form-prop__head";
        var lbl = document.createElement("div");
        lbl.className = "ss-form-prop__label";
        lbl.textContent = labelText;

        var exLbl = document.createElement("label");
        exLbl.className = "ss-form-prop__expose";
        var cb = document.createElement("input");
        cb.type = "checkbox";
        cb.checked = !!el.source_settings_expose[exportKey];
        cb.title = "When off, value is inlined in HTML only (omitted from template JSON).";
        cb.addEventListener("change", function () {
            el.source_settings_expose[exportKey] = cb.checked;
            pushHistoryDebounced();
            modelTouch();
        });
        var exText = document.createElement("span");
        exText.className = "ss-form-prop__expose-text";
        exText.textContent = "Expose in Source Settings (JSON)";
        exLbl.appendChild(cb);
        exLbl.appendChild(exText);

        head.appendChild(lbl);
        head.appendChild(exLbl);
        wrap.appendChild(head);
        wrap.appendChild(controlNode);
        return wrap;
    }

