/*
 * Spore Studio editor — vanilla JS implementation.
 *
 * The editor model lives in window.sporeState.model and is the single
 * source of truth. The DOM is rendered FROM the model on every change;
 * undo/redo is implemented as a snapshot stack of model JSON. Saves POST
 * the model to /api/spore-studio/save where the server compiles it into
 * HTML + JSON config.
 *
 * The plan called for GrapesJS, but its data model would need to be
 * marshalled bidirectionally into our spore.json schema (categories,
 * bindings, source variables) and the plan flagged that risk explicitly:
 * "treat GrapesJS as a view that we serialize to/from explicitly". A
 * thin custom canvas keeps the same UX (drag-drop blocks, properties,
 * undo, asset browser) while staying authoritative — every byte that
 * lands in saved HTML/JSON is generated by template_codegen on the
 * server, not extracted from a third-party DOM.
 */

