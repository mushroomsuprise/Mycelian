    function setupBlockPaletteDnD() {
        $$(".ss-block").forEach(function (block) {
            block.addEventListener("dragstart", function (ev) {
                ev.dataTransfer.setData("text/spore-block", block.dataset.blockType);
                ev.dataTransfer.effectAllowed = "copy";
                block.classList.add("ss-block--dragging");
            });
            block.addEventListener("dragend", function () {
                block.classList.remove("ss-block--dragging");
                clearCanvasDropHighlight();
            });
        });

        var stage = $("#ss-stage");
        stage.addEventListener("dragover", function (ev) {
            ev.preventDefault();
            ev.dataTransfer.dropEffect = "copy";
            updateCanvasDropHighlight(ev.clientX, ev.clientY, null, ev.altKey);
        });
        stage.addEventListener("dragleave", function (ev) {
            if (ev.target === stage && !stage.contains(ev.relatedTarget)) {
                clearCanvasDropHighlight();
            }
        });
        stage.addEventListener("drop", function (ev) {
            ev.preventDefault();
            clearCanvasDropHighlight();
            var blockType = ev.dataTransfer.getData("text/spore-block");
            var assetUrl = ev.dataTransfer.getData("text/spore-asset");
            var assetKind = ev.dataTransfer.getData("text/spore-asset-kind");
            var rect = stage.getBoundingClientRect();
            var parentPid =
                ev.altKey
                    ? null
                    : pickDropContainerId(
                        stage,
                        ev.clientX,
                        ev.clientY,
                        null
                    );
            var dropX = Math.max(0, Math.round(ev.clientX - rect.left));
            var dropY = Math.max(0, Math.round(ev.clientY - rect.top));
            if (parentPid) {
                var cnode =
                    $(".ss-element[data-spore-id=\"" + cssEscapeSs(parentPid) +
                        "\"]", stage);
                if (cnode) {
                    var cr = cnode.getBoundingClientRect();
                    dropX = Math.max(0, Math.round(ev.clientX - cr.left));
                    dropY = Math.max(0, Math.round(ev.clientY - cr.top));
                } else {
                    parentPid = null;
                }
            }

            if (blockType) {
                addElement(blockType, dropX, dropY, {}, parentPid || null);
            } else if (assetUrl) {
                var t = (assetKind === "video") ? "video"
                    : (assetKind === "audio") ? "audio"
                        : "image";
                addElement(t, dropX, dropY, { src: assetUrl }, parentPid || null);
            }
        });
    }

    function addElement(type, x, y, propsOverride, parentIdMaybe) {
        if (!state.model) { return; }
        if (!ELEMENT_PROP_SCHEMA[type]) { return; }
        if (isLegacyModel()) {
            toast(
                "Legacy templates can't accept new blocks — create a new " +
                "template via '+ New' to edit visually.",
                "error"
            );
            return;
        }
        promptCategory().then(function (category) {
            if (category === null) { return; }
            var pid = pidNorm(parentIdMaybe);
            if (pid) {
                var par = selectedElementMatchingId(pid);
                if (!par || par.type !== "container") {
                    pid = null;
                }
            }
            var id = uniqueElementId(type);
            var sz = DEFAULT_SIZE[type] || { w: 100, h: 30 };
            var props = Object.assign({}, DEFAULT_PROPS[type] || {}, propsOverride || {});
            var el = {
                id: id,
                type: type,
                category: category,
                position: { x: x, y: y },
                size: { w: sz.w, h: sz.h },
                props: props,
                bindings: []
            };
            if (pid) {
                el.parent_id = pid;
            }
            ensureElementExposeDefaults(el);
            ensureElementAnimations(el);
            if (type === "text" || type === "marquee") { ensureTextModeDefaults(el); }
            if (type === "image") { ensureImageSrcDefaults(el); }
            if (type === "progress_bar") { ensureProgressBarDefaults(el); }
            if (type === "shape") { ensureShapeDefaults(el); }
            if (type === "divider") { ensureDividerDefaults(el); }
            if (type === "gradient") { ensureGradientDefaults(el); }
            if (type === "marquee") { ensureMarqueeDefaults(el); }
            if (type === "clock") { ensureClockDefaults(el); }
            if (type === "timer") { ensureTimerDefaults(el); }
            if (pid) { ensurePlacementDefaults(el); }
            state.model.elements = state.model.elements || [];
            state.model.elements.push(el);
            normalizeParentLinksAndReorderLive();
            onLayoutTimingChanged();
            state.selectedId = id;
            pushHistory();
            renderAll();
            modelTouch();
        });
    }

    /** Find ``{id}`` anywhere in ``state.model.elements`` (not necessarily selected). */
    function selectedElementMatchingId(anId) {
        if (!state.model || !anId) {
            return null;
        }
        for (var i = 0; i < state.model.elements.length; i++) {
            if (state.model.elements[i].id === anId) {
                return state.model.elements[i];
            }
        }
        return null;
    }

    function existingCategories() {
        var seen = {};
        var out = [];
        (state.model && state.model.elements ? state.model.elements : [])
            .forEach(function (el) {
                var c = (el.category || "").trim();
                if (c && !seen[c]) { seen[c] = true; out.push(c); }
            });
        return out;
    }

    /**
     * Show the category picker modal. Returns a Promise that resolves to a
     * non-empty category string, or null if the user cancelled. Falls back
     * to a free-text input when no existing categories are available.
     */
    function promptCategory() {
        return new Promise(function (resolve) {
            var tpl = $("#ss-category-template");
            var node = tpl.content.firstElementChild.cloneNode(true);
            document.body.appendChild(node);

            var sel = node.querySelector("[data-cat='select']");
            var newRow = node.querySelector("[data-cat='new-row']");
            var newInput = node.querySelector("[data-cat='new']");
            var selectRow = node.querySelector("[data-cat='select-row']");

            var categories = existingCategories();
            var NEW_VALUE = "__ss_new__";

            if (categories.length === 0) {
                selectRow.style.display = "none";
                newInput.value = "Elements";
            } else {
                categories.forEach(function (c) {
                    var op = document.createElement("option");
                    op.value = c;
                    op.textContent = c;
                    sel.appendChild(op);
                });
                var newOp = document.createElement("option");
                newOp.value = NEW_VALUE;
                newOp.textContent = "+ New category…";
                sel.appendChild(newOp);
                sel.value = categories[categories.length - 1];
                newRow.style.display = "none";
                sel.addEventListener("change", function () {
                    if (sel.value === NEW_VALUE) {
                        newRow.style.display = "";
                        newInput.value = "";
                        newInput.focus();
                    } else {
                        newRow.style.display = "none";
                    }
                });
            }

            function close(value) { node.remove(); resolve(value); }

            node.querySelector("[data-cat-action='cancel']")
                .addEventListener("click", function () { close(null); });
            node.querySelector("[data-cat-action='ok']")
                .addEventListener("click", function () {
                    var value;
                    if (categories.length === 0 || sel.value === NEW_VALUE) {
                        value = (newInput.value || "").trim();
                        if (!value) { value = "Elements"; }
                    } else {
                        value = sel.value;
                    }
                    close(value);
                });
            newInput.addEventListener("keydown", function (ev) {
                if (ev.key === "Enter") {
                    ev.preventDefault();
                    node.querySelector("[data-cat-action='ok']").click();
                }
            });
        });
    }

